import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const latency=require('../cosmic-latency-core.js');
const coreSource=fs.readFileSync(new URL('../cosmic-latency-core.js',import.meta.url),'utf8');
const viewSource=fs.readFileSync(new URL('../cosmic-latency.js',import.meta.url),'utf8');
const styles=fs.readFileSync(new URL('../cosmic-latency.css',import.meta.url),'utf8');
const loader=fs.readFileSync(new URL('../cosmic-signal.js',import.meta.url),'utf8');
const worker=fs.readFileSync(new URL('../service-worker.js',import.meta.url),'utf8');
const notes=fs.readFileSync(new URL('../COSMIC_RECEIVE_DESK.md',import.meta.url),'utf8');
assert.equal(latency.LANDMARKS.length,7);
assert.deepEqual(latency.LANDMARKS.map(x=>x.id),['moon','sun','alpha-centauri','sirius','galactic-center','andromeda','cmb']);
const [moon,sun,alpha,,,andromeda,cmb]=latency.LANDMARKS;
assert.ok(Math.abs(moon.delaySeconds-1.28221)<0.0001);
assert.ok(Math.abs(sun.delaySeconds-501.00132)<0.0001);
assert.equal(alpha.delaySeconds,4.37*latency.SECONDS_PER_YEAR);
assert.equal(andromeda.delaySeconds,2.5e6*latency.SECONDS_PER_YEAR);
assert.equal(cmb.delaySeconds,13.8e9*latency.SECONDS_PER_YEAR);
const positions=latency.LANDMARKS.map(x=>latency.logPosition(x.delaySeconds));
assert.equal(positions[0],0); assert.equal(positions.at(-1),100);
for(let i=1;i<positions.length;i+=1) assert.ok(positions[i]>positions[i-1]);
assert.equal(latency.formatDelay(moon.delaySeconds),'~1.28 seconds');
assert.equal(latency.formatDelay(sun.delaySeconds),'~8 min 21 sec');
assert.equal(latency.formatDelay(alpha.delaySeconds),'~4.37 years');
assert.equal(latency.formatDelay(26000*latency.SECONDS_PER_YEAR),'~26,000 years');
assert.equal(latency.formatDelay(andromeda.delaySeconds),'~2.5 million years');
assert.equal(latency.formatDelay(cmb.delaySeconds),'~13.8 billion years');
const reception=Date.UTC(2026,7,7,16,0,0);
assert.equal(latency.formatUtc(reception),'2026-08-07 16:00:00 UTC');
assert.equal(latency.departureLabel(reception,sun),'2026-08-07 15:51:39 UTC');
assert.equal(latency.departureLabel(reception,andromeda),'~2.5 million years before reception');
assert.match(latency.sentence(reception,andromeda),/2\.5 million years earlier/);
assert.match(viewSource,/THE LATENCY OF NOW/);
assert.match(viewSource,/section\.id='cosmic-latency'/);
assert.match(viewSource,/No new runtime request/i);
assert.match(viewSource,/href="COSMIC_RECEIVE_DESK\.md"/);
assert.match(worker,/['"]\.\/COSMIC_RECEIVE_DESK\.md['"]/);
assert.match(notes,/The world is doing this without us\./);
assert.match(notes,/science\.nasa\.gov\/universe\/overview/);
assert.match(loader,/cosmic-latency-core\.js/);
assert.match(loader,/cosmic-latency\.js/);
assert.doesNotMatch(coreSource+viewSource,/https?:\/\//i);
assert.doesNotMatch(coreSource+viewSource,/\bfetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket|EventSource/i);
assert.doesNotMatch(coreSource+viewSource,/setInterval|requestAnimationFrame|localStorage|sessionStorage|indexedDB|document\.cookie|navigator\.geolocation/i);
assert.match(styles,/@media \(max-width: 760px\)/);
assert.match(styles,/@media \(max-width: 380px\)/);
assert.match(styles,/@media \(prefers-reduced-motion: reduce\)/);
assert.match(styles,/@media \(prefers-contrast: more\)/);
assert.match(styles,/@media print/);
assert.doesNotMatch(styles,/@import\s+url|font-face|https?:\/\//i);
console.log('Cosmic Receive Desk light-delay constants, logarithmic rail, local-only runtime, accessibility hooks, and deep-time honesty verified.');
